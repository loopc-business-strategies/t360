export function getCategoryMeta(slug: string): CategoryMeta | undefined {
  return CATEGORY_META[slug];
}

export function resolveRelatedCategorySlugs(leafSlug: string): string[] {
  const meta = CATEGORY_META[leafSlug];
  if (!meta) return [leafSlug];
  const out = [leafSlug, ...meta.compatibleRelated];
  for (const [slug, m] of Object.entries(CATEGORY_META)) {
    if (slug === leafSlug) continue;
    if (m.segment === meta.segment && m.productType === meta.productType && !out.includes(slug)) {
      out.push(slug);
    }
  }
  return out;
}

export function totalDemoQuota(): number {
  return Object.values(CATEGORY_META).reduce((n, m) => n + m.quota, 0);
}

export function priceForBand(band: PriceBand, i: number): { price: number; salePrice: number | null } {
  const table: Record<PriceBand, number> = {
    tee: 399 + (i % 8) * 200,
    shirt: 699 + (i % 8) * 288,
    bottom: 999 + (i % 7) * 400,
    outer: 1499 + (i % 6) * 500,
    dress: 799 + (i % 8) * 500,
    ethnic: 899 + (i % 8) * 500,
    saree: 1499 + (i % 10) * 1200,
    bridal: 3999 + (i % 8) * 2500,
    kids: 399 + (i % 7) * 250,
  };
  const price = table[band] ?? 999;
  const onSale = i % 4 === 0;
  return { price, salePrice: onSale ? Math.round(price * 0.85) : null };
}


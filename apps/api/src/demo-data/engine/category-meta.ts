export type SizeProfile = "adult" | "kids" | "waist" | "one";
export type PriceBand =
  | "tee"
  | "shirt"
  | "bottom"
  | "outer"
  | "dress"
  | "ethnic"
  | "saree"
  | "bridal"
  | "kids";

export type CategoryMeta = {
  slug: string;
  segment: string;
  gender: "men" | "women" | "kids" | "unisex";
  productType: string;
  subType: string;
  tryOnSupported: boolean;
  compatibleRelated: string[];
  sizeProfile: SizeProfile;
  priceBand: PriceBand;
  nameTokens: string[];
  descTokens: string[];
  skuType: string;
  brandSlug: string;
  quota: number;
};

function m(
  partial: Omit<CategoryMeta, "nameTokens" | "descTokens"> & {
    nameTokens?: string[];
    descTokens?: string[];
  },
): CategoryMeta {
  const nameTokens = partial.nameTokens ?? [partial.subType.replace(/-/g, " ")];
  const descTokens = partial.descTokens ?? nameTokens;
  return { ...partial, nameTokens, descTokens };
}

